import { describe, it, expect } from 'vitest';
import { findBanned, scanTsx, scanJson } from '../../scripts/check-copy';

describe('check-copy', () => {
  it('flags banned words as whole words, case-insensitive', () => {
    expect(findBanned('AI-powered notes')).toBeTruthy();
    expect(findBanned('Generate report')).toBe('Generate');
    expect(findBanned('Clinical intelligence platform')).toBeTruthy();
    expect(findBanned('Prepare report')).toBeNull();
    // whole-word only: "said", "maintain", "remodel" must not match
    expect(findBanned('She said the remodelled ward was maintained')).toBeNull();
  });

  it('flags banned icon names', () => {
    expect(findBanned('smart_toy')).toBe('smart_toy');
    expect(findBanned('auto_awesome')).toBe('auto_awesome');
    expect(findBanned('fact_check')).toBeNull();
  });

  it('respects the allowlist', () => {
    expect(findBanned('Clinical Assistant', ['clinical assistant'])).toBeNull();
    expect(findBanned('Ask the assistant', ['clinical assistant'])).toBe('assistant');
  });

  it('checks JSX text and string literals but not identifiers, imports or comparisons', () => {
    const src = `
      import { aiThing } from 'ai';
      type K = 'ai' | 'worker';
      const createdBy: K = 'worker';
      export function X({ k }: { k: K }) {
        const model = 1;
        if (k === 'ai') return null;
        return <div className="model">Organise notes {model}</div>;
      }
      export const Y = () => <p>AI Synthesis</p>;
      export const Z = () => <span title="Regenerate with AI">x</span>;
    `;
    const hits = scanTsx(src, 'x.tsx');
    expect(hits.map((h) => h.match)).toEqual(['AI', 'AI']);
  });

  it('scans message catalogues', () => {
    const hits = scanJson(JSON.stringify({ a: { b: 'Generated by our model' }, c: 'Save draft' }), 'eng.json');
    expect(hits).toHaveLength(1);
    expect(hits[0].text).toContain('a.b');
  });
});
